--- Приложение с кэшем и сессиями на спейсах — для живой проверки первого
--- применения на пустой базе.
---
--- Спейсы заводят шаги миграции, а миграции ядро поднимает событием после
--- применения роли. Кэш приложения собирается при применении, хранилище
--- сессий — ещё раньше, при загрузке роли, когда box не поднят вовсе:
--- спейс по имени оба ищут первым обращением.
local fio = require('fio')

local cache = require('tnt.cache')

--- Корень раскладки — каталог над этим файлом: рабочий каталог узла
--- временный, и относительный путь оттуда не ведёт никуда.
local root = fio.dirname(fio.dirname(fio.abspath(assert(debug.getinfo(1, 'S')).source:sub(2))))

--- Приставка модулей — от имени, которым узел загрузил роль: от какого
--- каталога пути поиска лежит образец, решает помощник проверок, а не он.
---@type string
local name = ...

return require('tnt.framework').new({
    name = 'space.cache',
    base = root,
    prefix = (name:gsub('%.bootstrap%.app$', '')),
    -- Сессии на своём спейсе, не общем с кэшем: `flush` кэша их не заденет.
    session = {
        cache = cache.new({ driver = 'space', space = 'app_sessions', prefix = 'sess:' }),
    },
})
