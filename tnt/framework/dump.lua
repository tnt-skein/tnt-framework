--- Показ значения на странице: директива `@dump`.
---
--- Тому, кто собирает страницу, нужно видеть данные, которые в неё пришли,
--- там же, где они рисуются: журнал узла лежит на другой машине, а страница
--- уже открыта. Директива пишет значение показом `tnt-debug`:
---
---     <pre>@dump(customer)</pre>
---     --> <pre>{
---     -->     name = &quot;Иван&quot;,
---     -->     password = [скрыто]
---     --> }</pre>
---
--- Показ, а не `tostring` и не JSON: ключи идут в постоянном порядке, род
--- значения виден, тайны под своими именами скрыты, пределы глубины и длины
--- держатся, и броска нет ни на каком значении — страница не падает оттого,
--- что на неё смотрят.
---
--- Директива вывода, а не разметки: ответ экранируется, и строка из данных
--- с `<script>` выходит текстом. Показ многострочный, и переводы строк
--- сохраняет `<pre>` вокруг директивы.
---
--- Значений несколько — каждое своим показом, через запятую с переводом
--- строки, как `dump` пакета пишет их одной записью: `@dump(order, total)`.
--- Лишнее значение не пропадает молча, а `nil` среди них показывается
--- словом `nil`: страницу смотрят ровно затем, чтобы увидеть пустоту.

local dbg = require('tnt.debug')

local Module = {}

--- Имя директивы.
Module.NAME = 'dump'

--- Показ значений директивы; без значений — пусто.
---@param ... any Значения из данных страницы
---@return string
function Module.show(...)
    local shown = {}

    -- Счёт — по `select('#')`: длина таблицы значений с `nil` внутри
    -- не определена, и показ мог бы оборваться на пустоте.
    for at = 1, select('#', ...) do
        shown[at] = dbg.describe((select(at, ...)))
    end

    return table.concat(shown, ',\n')
end

return Module
