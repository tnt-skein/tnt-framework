--- Канонический адрес страницы: директива `@canonical`.
---
--- Одну страницу открывают по многим адресам — с меткой рассылки,
--- с порядком сортировки, по второму имени узла, — и `<link rel="canonical">`
--- называет поисковику один. Адрес собирает роутер приложения от адреса
--- `http.url` (`route.canonical(request, { query = { 'page' } })`)
--- и кладёт в данные страницы, а директива пишет по нему тег:
---
---     @canonical(canonical)
---     --> <link rel="canonical" href="https://shop.example.org/articles?page=2">
---
--- Тег стоит в рамке сайта, одной на все страницы, а адрес есть не у каждой
--- из них. Страница без адреса не получает ничего, а не `href=""`: пустой
--- адрес браузер и поисковик читают как адрес самой страницы — со всеми
--- метками рассылки, от которых канонический адрес и спасал.
---
--- Тег пишется директивой разметки (`views:markup`): ответ обычной
--- директивы экранируется, и тег вышел бы текстом. Экранируется здесь
--- только адрес — `&` между полями становится `&amp;`, как и положено
--- в значении атрибута.

local template = require('tnt.template')

local Module = {}

--- Имя директивы.
Module.NAME = 'canonical'

--- Тег канонического адреса; адреса нет — пустота.
---
--- Адрес не строкой — промах того, кто собирал данные страницы, и бросок
--- винит строку шаблона: уровень 2 — переведённый шаблон, который позвал
--- директиву, и в тексте стоят его имя и строка.
---@param address any Адрес из данных страницы
---@return string
function Module.link(address)
    if address == nil or address == '' then
        return ''
    end

    if type(address) ~= 'string' then
        error(('@canonical ждёт адрес строкой, а не %s'):format(type(address)), 2)
    end

    return ('<link rel="canonical" href="%s">'):format(template.escape(address))
end

return Module
