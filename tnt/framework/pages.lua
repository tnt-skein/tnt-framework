--- Страницы отказов приложения: 404 и 500 на рамке сайта.
---
--- Человек, попавший на несуществующий адрес, должен увидеть сайт,
--- а не голое тело отказа: ту же шапку, то же меню, ту же ссылку
--- «на главную». Поэтому страницы отказов — обычные шаблоны приложения
--- и живут там же, где остальные: `resources/views/errors/404.thtml.lua`.
---
--- Шаблон ищется по коду ответа, а чего нет — общим `errors/error`:
--- приложению довольно одной страницы на все отказы, а завести отдельную
--- он вправе тогда, когда ей есть что сказать своего. Нет ни одной —
--- страницу рисует сам пакет отказов, встроенную.
---
--- Имена шаблонов читаются один раз, при сборке приложения, а не
--- на каждом отказе: обход каталога на каждый промах по адресу — это
--- работа с диском ровно там, где узел уже отвечает отказом. Правка
--- страницы при этом не теряется: движок и весь этот список свои
--- на каждое применение конфигурации, и `config:reload()` перечитывает
--- оба.
---
--- Данные страницы приходят от пакета отказов (`TntErrorPageView`): код
--- ответа, заголовок по коду, слово для человека, номера происшествия
--- и запроса. Подробностей поломки — места в коде, стека, заголовков —
--- среди них нет никогда: страницу разбора пакет рисует сам, и шаблон
--- приложения её ни показать, ни утечь не может.

local template = require('tnt.template')

local Module = {}

--- Каталог страниц отказов внутри каталога страниц приложения.
Module.DIRECTORY = 'errors'

--- Имя общей страницы — той, что отвечает за все коды без своей.
Module.COMMON = 'error'

--- Имя шаблона по коду ответа: `errors.404`.
---@param what string|integer
---@return string
local function named(what)
    return ('%s.%s'):format(Module.DIRECTORY, what)
end

--- Собирает рисовальщика страниц отказа по каталогу движка.
---
--- Пусто — страниц у приложения нет вовсе (`views = false`), и спрашивать
--- рисовальщика не о чем. Приложение со страницами, но без страниц
--- отказа, рисовальщика получает: он отвечает пустотой на каждый код,
--- и пакет отказов показывает встроенную страницу. Отдельной проверки
--- «есть ли у него хоть одна» здесь нет нарочно — она различала бы два
--- состояния, в которых человек видит одну и ту же страницу.
---@param view TntTemplateEngine|nil Движок страниц приложения
---@return (fun(shown: TntErrorPageView): string|nil)|nil
function Module.of(view)
    if view == nil then
        return nil
    end

    local known = {}

    for _, name in ipairs(template.names(view)) do
        known[name] = true
    end

    return function(shown)
        local own = named(shown.status)

        if known[own] then
            return view:render(own, shown)
        end

        local common = named(Module.COMMON)

        if known[common] then
            return view:render(common, shown)
        end

        -- Ни своей страницы, ни общей: пусть рисует встроенная. Бросок
        -- здесь был бы хуже — отказ остался бы без ответа.
        return nil
    end
end

return Module
